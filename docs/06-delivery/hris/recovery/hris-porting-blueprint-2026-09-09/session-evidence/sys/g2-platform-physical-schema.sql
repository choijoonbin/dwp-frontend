CREATE OR REPLACE FUNCTION sys_guard_config_publication_lineage() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.published_at IS NOT NULL THEN
            RAISE EXCEPTION 'SYS_CONFIG_PUBLISHED_VERSION_CANNOT_BE_DELETED' USING ERRCODE = '55000';
        END IF;
        RETURN OLD;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.published_at IS NOT NULL THEN
        IF NEW.published_at IS DISTINCT FROM OLD.published_at
           OR NEW.config_set_id IS DISTINCT FROM OLD.config_set_id
           OR NEW.effective_from IS DISTINCT FROM OLD.effective_from
           OR NEW.schema_key IS DISTINCT FROM OLD.schema_key
           OR NEW.schema_version IS DISTINCT FROM OLD.schema_version
           OR NEW.payload IS DISTINCT FROM OLD.payload
           OR NEW.payload_digest IS DISTINCT FROM OLD.payload_digest THEN
            RAISE EXCEPTION 'SYS_CONFIG_PUBLISHED_LINEAGE_IMMUTABLE' USING ERRCODE = '55000';
        END IF;
        IF NEW.effective_to IS DISTINCT FROM OLD.effective_to
           AND NOT (
               OLD.effective_to IS NULL
               AND NEW.effective_to IS NOT NULL
               AND NEW.effective_to > OLD.effective_from
           ) THEN
            RAISE EXCEPTION 'SYS_CONFIG_PUBLISHED_PERIOD_REWRITE_FORBIDDEN' USING ERRCODE = '55000';
        END IF;
        IF OLD.lifecycle_state = 'RETIRED' AND NEW.lifecycle_state <> 'RETIRED' THEN
            RAISE EXCEPTION 'SYS_CONFIG_RETIREMENT_MONOTONIC' USING ERRCODE = '55000';
        END IF;
        IF NEW.lifecycle_state NOT IN ('PUBLISHED','RETIRED') THEN
            RAISE EXCEPTION 'SYS_CONFIG_PUBLISHED_STATE_REWIND' USING ERRCODE = '55000';
        END IF;
    ELSIF NEW.lifecycle_state IN ('PUBLISHED','RETIRED') THEN
        NEW.published_at := COALESCE(NEW.published_at, CURRENT_TIMESTAMP);
    ELSIF NEW.published_at IS NOT NULL THEN
        RAISE EXCEPTION 'SYS_CONFIG_PUBLICATION_MARKER_WITHOUT_PUBLISHED_STATE' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sys_hris_config_publication_lineage
    BEFORE INSERT OR UPDATE OR DELETE ON sys_hris_config_versions
    FOR EACH ROW EXECUTE FUNCTION sys_guard_config_publication_lineage();


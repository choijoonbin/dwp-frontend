        AND (state <> 'REVOKED' OR (revoked_by IS NOT NULL AND revoked_at IS NOT NULL))
    )
);

CREATE OR REPLACE FUNCTION sys_guard_extension_pack_lifecycle() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.lifecycle_state <> 'DISCOVERED' THEN
            RAISE EXCEPTION 'SYS_EXTENSION_PACK_MUST_START_DISCOVERED' USING ERRCODE = '55000';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'SYS_EXTENSION_PACK_VERSION_CANNOT_BE_DELETED' USING ERRCODE = '55000';
    END IF;
    IF OLD.lifecycle_state = 'REVOKED' AND NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'SYS_EXTENSION_PACK_REVOCATION_MONOTONIC' USING ERRCODE = '55000';
    END IF;
    IF OLD.lifecycle_state <> NEW.lifecycle_state AND NOT (
        (OLD.lifecycle_state = 'DISCOVERED' AND NEW.lifecycle_state = 'VERIFIED')
        OR (OLD.lifecycle_state = 'VERIFIED' AND NEW.lifecycle_state = 'APPROVED')
        OR (OLD.lifecycle_state IN ('DISCOVERED','VERIFIED','APPROVED') AND NEW.lifecycle_state = 'REVOKED')
    ) THEN
        RAISE EXCEPTION 'SYS_EXTENSION_PACK_INVALID_STATE_TRANSITION' USING ERRCODE = '55000';
    END IF;
    IF OLD.lifecycle_state IN ('VERIFIED','APPROVED','REVOKED')
       AND ROW(NEW.extension_key, NEW.version, NEW.pack_kind, NEW.manifest,
               NEW.manifest_digest, NEW.signature_key_id, NEW.signature,
               NEW.signature_digest, NEW.compatibility_range, NEW.compatibility_digest,
               NEW.hook_allowlist_digest, NEW.schema_digest, NEW.license_digest,
               NEW.permission_manifest_digest, NEW.discovered_by)
           IS DISTINCT FROM
           ROW(OLD.extension_key, OLD.version, OLD.pack_kind, OLD.manifest,
               OLD.manifest_digest, OLD.signature_key_id, OLD.signature,
               OLD.signature_digest, OLD.compatibility_range, OLD.compatibility_digest,
               OLD.hook_allowlist_digest, OLD.schema_digest, OLD.license_digest,
               OLD.permission_manifest_digest, OLD.discovered_by) THEN
        RAISE EXCEPTION 'SYS_EXTENSION_PACK_VERIFIED_CONTENT_IMMUTABLE' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION sys_guard_tenant_extension_lifecycle() RETURNS trigger AS $$
DECLARE pack_state VARCHAR(24);
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'SYS_TENANT_EXTENSION_INSTALLATION_CANNOT_BE_DELETED' USING ERRCODE = '55000';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.state <> 'REQUESTED' THEN
            RAISE EXCEPTION 'SYS_TENANT_EXTENSION_MUST_START_REQUESTED' USING ERRCODE = '55000';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF OLD.state = 'REVOKED' AND NEW IS DISTINCT FROM OLD THEN
            RAISE EXCEPTION 'SYS_TENANT_EXTENSION_REVOCATION_MONOTONIC' USING ERRCODE = '55000';
        END IF;
        IF ROW(NEW.tenant_id, NEW.public_id, NEW.extension_version_id, NEW.config_ref,
               NEW.config_digest, NEW.manifest_digest, NEW.signature_digest,
               NEW.compatibility_digest, NEW.approval_workflow_key, NEW.request_digest,
               NEW.requested_by, NEW.requested_at)
           IS DISTINCT FROM
           ROW(OLD.tenant_id, OLD.public_id, OLD.extension_version_id, OLD.config_ref,
               OLD.config_digest, OLD.manifest_digest, OLD.signature_digest,
               OLD.compatibility_digest, OLD.approval_workflow_key, OLD.request_digest,
               OLD.requested_by, OLD.requested_at) THEN
            RAISE EXCEPTION 'SYS_TENANT_EXTENSION_REQUEST_IDENTITY_IMMUTABLE' USING ERRCODE = '55000';
        END IF;
        IF OLD.state <> NEW.state AND NOT (
            (OLD.state = 'REQUESTED' AND NEW.state IN ('PENDING_APPROVAL','FAILED','REVOKED'))
            OR (OLD.state = 'PENDING_APPROVAL' AND NEW.state IN ('APPROVED','FAILED','REVOKED'))
            OR (OLD.state = 'APPROVED' AND NEW.state IN ('INSTALLING','FAILED','REVOKED'))
            OR (OLD.state = 'INSTALLING' AND NEW.state IN ('INSTALLED_DISABLED','FAILED','REVOKED'))
            OR (OLD.state = 'INSTALLED_DISABLED' AND NEW.state IN ('ENABLED','SUSPENDED','REVOKED'))
            OR (OLD.state = 'ENABLED' AND NEW.state IN ('SUSPENDED','REVOKED'))
            OR (OLD.state = 'SUSPENDED' AND NEW.state IN ('ENABLED','REVOKED'))
            OR (OLD.state = 'FAILED' AND NEW.state IN ('REQUESTED','REVOKED'))
        ) THEN
            RAISE EXCEPTION 'SYS_TENANT_EXTENSION_INVALID_STATE_TRANSITION' USING ERRCODE = '55000';
        END IF;
    END IF;
    IF NEW.state IN ('INSTALLING','INSTALLED_DISABLED','ENABLED','SUSPENDED') THEN
        SELECT lifecycle_state INTO pack_state
          FROM sys_extension_pack_versions
         WHERE extension_version_id = NEW.extension_version_id;
        IF pack_state IS DISTINCT FROM 'APPROVED' THEN
            RAISE EXCEPTION 'SYS_EXTENSION_PACK_NOT_APPROVED' USING ERRCODE = '55000';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION sys_cascade_extension_pack_revocation() RETURNS trigger AS $$
BEGIN
    IF OLD.lifecycle_state <> 'REVOKED' AND NEW.lifecycle_state = 'REVOKED' THEN
        UPDATE sys_tenant_extension_installations
           SET state = 'REVOKED',
               revoked_by = NEW.revoked_by,
               revoked_at = NEW.revoked_at,
               version = version + 1
         WHERE extension_version_id = NEW.extension_version_id
           AND state <> 'REVOKED';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public;

CREATE TRIGGER tr_sys_extension_pack_lifecycle
    BEFORE INSERT OR UPDATE OR DELETE ON sys_extension_pack_versions
    FOR EACH ROW EXECUTE FUNCTION sys_guard_extension_pack_lifecycle();
CREATE TRIGGER tr_sys_tenant_extension_lifecycle
    BEFORE INSERT OR UPDATE OR DELETE ON sys_tenant_extension_installations
    FOR EACH ROW EXECUTE FUNCTION sys_guard_tenant_extension_lifecycle();
CREATE TRIGGER tr_sys_extension_pack_revoke_cascade
    AFTER UPDATE OF lifecycle_state ON sys_extension_pack_versions
    FOR EACH ROW EXECUTE FUNCTION sys_cascade_extension_pack_revocation();


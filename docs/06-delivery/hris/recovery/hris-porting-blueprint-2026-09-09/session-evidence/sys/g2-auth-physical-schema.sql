CREATE OR REPLACE FUNCTION com_guard_product_access_assignment_lifecycle() RETURNS trigger AS $$
DECLARE package_state VARCHAR(24);
DECLARE projection_count INTEGER;
DECLARE applied_projection_count INTEGER;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.lifecycle_state <> 'DRAFT' THEN
            RAISE EXCEPTION 'PRODUCT_ACCESS_ASSIGNMENT_MUST_START_DRAFT' USING ERRCODE = '55000';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_ASSIGNMENT_HISTORY_CANNOT_BE_DELETED' USING ERRCODE = '55000';
    END IF;
    IF OLD.lifecycle_state IN ('REVOKED','EXPIRED','REJECTED') AND NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_ASSIGNMENT_TERMINAL_STATE_MONOTONIC' USING ERRCODE = '55000';
    END IF;
    IF ROW(NEW.tenant_id, NEW.public_id, NEW.package_id, NEW.package_public_id,
           NEW.package_catalog_version, NEW.principal_type, NEW.principal_public_id,
           NEW.scope_fingerprint, NEW.valid_from, NEW.source_kind, NEW.source_reference,
           NEW.authored_by, NEW.created_at)
       IS DISTINCT FROM
       ROW(OLD.tenant_id, OLD.public_id, OLD.package_id, OLD.package_public_id,
           OLD.package_catalog_version, OLD.principal_type, OLD.principal_public_id,
           OLD.scope_fingerprint, OLD.valid_from, OLD.source_kind, OLD.source_reference,
           OLD.authored_by, OLD.created_at) THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_ASSIGNMENT_IDENTITY_IMMUTABLE' USING ERRCODE = '55000';
    END IF;
    IF NEW.valid_to IS DISTINCT FROM OLD.valid_to
       AND NOT (OLD.valid_to IS NULL AND NEW.valid_to IS NOT NULL AND NEW.valid_to > OLD.valid_from) THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_ASSIGNMENT_PERIOD_REWRITE' USING ERRCODE = '55000';
    END IF;
    IF (OLD.approved_by IS NOT NULL AND ROW(NEW.approved_by, NEW.approved_at)
                                      IS DISTINCT FROM ROW(OLD.approved_by, OLD.approved_at))
       OR (OLD.activated_by IS NOT NULL AND ROW(NEW.activated_by, NEW.activated_at)
                                         IS DISTINCT FROM ROW(OLD.activated_by, OLD.activated_at))
       OR (OLD.revoked_by IS NOT NULL AND ROW(NEW.revoked_by, NEW.revoked_at)
                                       IS DISTINCT FROM ROW(OLD.revoked_by, OLD.revoked_at)) THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_ASSIGNMENT_EVIDENCE_IMMUTABLE' USING ERRCODE = '55000';
    END IF;
    IF OLD.lifecycle_state <> NEW.lifecycle_state AND NOT (
        (OLD.lifecycle_state = 'DRAFT' AND NEW.lifecycle_state = 'PENDING_APPROVAL')
        OR (OLD.lifecycle_state = 'PENDING_APPROVAL' AND NEW.lifecycle_state IN ('DRAFT','APPROVED','REJECTED'))
        OR (OLD.lifecycle_state = 'APPROVED' AND NEW.lifecycle_state IN ('PENDING_PROJECTION','REVOKED','EXPIRED'))
        OR (OLD.lifecycle_state = 'PENDING_PROJECTION' AND NEW.lifecycle_state IN ('ACTIVE','DEGRADED','REVOKED','EXPIRED'))
        OR (OLD.lifecycle_state = 'ACTIVE' AND NEW.lifecycle_state IN ('DEGRADED','SUSPENDED','REVOKED','EXPIRED'))
        OR (OLD.lifecycle_state = 'DEGRADED' AND NEW.lifecycle_state IN ('PENDING_PROJECTION','SUSPENDED','REVOKED','EXPIRED'))
        OR (OLD.lifecycle_state = 'SUSPENDED' AND NEW.lifecycle_state IN ('PENDING_PROJECTION','REVOKED','EXPIRED'))
    ) THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_ASSIGNMENT_INVALID_STATE_TRANSITION' USING ERRCODE = '55000';
    END IF;
    IF NEW.lifecycle_state IN ('PENDING_PROJECTION','ACTIVE') THEN
        SELECT lifecycle_state INTO package_state
          FROM sys_product_access_package_catalog
         WHERE package_id = NEW.package_id;
        IF package_state IS DISTINCT FROM 'ACTIVE' THEN
            RAISE EXCEPTION 'PRODUCT_ACCESS_PACKAGE_NOT_ACTIVE' USING ERRCODE = '55000';
        END IF;
    END IF;
    IF NEW.lifecycle_state = 'ACTIVE' AND OLD.lifecycle_state <> 'ACTIVE' THEN
        SELECT count(*), count(DISTINCT projection_kind) FILTER (
                   WHERE state = 'APPLIED'
                     AND applied_revision = expected_revision
                     AND receipt_public_id IS NOT NULL
                     AND applied_at IS NOT NULL
               )
          INTO projection_count, applied_projection_count
          FROM com_product_access_package_projection_status
         WHERE tenant_id = NEW.tenant_id AND assignment_id = NEW.assignment_id;
        IF projection_count <> 5 OR applied_projection_count <> 5 THEN
            RAISE EXCEPTION 'PRODUCT_ACCESS_PROJECTION_CLOSURE_INCOMPLETE' USING ERRCODE = '55000';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION com_guard_product_access_projection_lifecycle() RETURNS trigger AS $$
DECLARE assignment_state VARCHAR(32);
BEGIN
    IF TG_OP = 'INSERT' THEN
        SELECT lifecycle_state INTO assignment_state
          FROM com_product_access_package_assignments
         WHERE tenant_id = NEW.tenant_id AND assignment_id = NEW.assignment_id;
        IF assignment_state = 'ACTIVE' THEN
            RAISE EXCEPTION 'ACTIVE_PRODUCT_ACCESS_PROJECTION_SET_IMMUTABLE' USING ERRCODE = '55000';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        SELECT lifecycle_state INTO assignment_state
          FROM com_product_access_package_assignments
         WHERE tenant_id = OLD.tenant_id AND assignment_id = OLD.assignment_id;
        IF assignment_state = 'ACTIVE' THEN
            RAISE EXCEPTION 'ACTIVE_PRODUCT_ACCESS_PROJECTION_CANNOT_BE_DELETED' USING ERRCODE = '55000';
        END IF;
        RETURN OLD;
    END IF;
    IF ROW(NEW.tenant_id, NEW.assignment_id, NEW.projection_owner, NEW.projection_kind)
       IS DISTINCT FROM
       ROW(OLD.tenant_id, OLD.assignment_id, OLD.projection_owner, OLD.projection_kind) THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_PROJECTION_IDENTITY_IMMUTABLE' USING ERRCODE = '55000';
    END IF;
    SELECT lifecycle_state INTO assignment_state
      FROM com_product_access_package_assignments
     WHERE tenant_id = OLD.tenant_id AND assignment_id = OLD.assignment_id;
    IF assignment_state = 'ACTIVE' AND NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'ACTIVE_PRODUCT_ACCESS_PROJECTION_MUST_REMAIN_APPLIED' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


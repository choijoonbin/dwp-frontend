CREATE TABLE sys_product_access_package_catalog (
    package_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    product_key VARCHAR(80) NOT NULL,
    package_code VARCHAR(120) NOT NULL,
    catalog_version INTEGER NOT NULL CHECK (catalog_version > 0),
    lifecycle_state VARCHAR(24) NOT NULL CHECK (lifecycle_state IN ('DRAFT','ACTIVE','RETIRED')),
    risk_level VARCHAR(16) NOT NULL CHECK (risk_level IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    app_resource_key VARCHAR(120) NOT NULL,
    display_name_key VARCHAR(240) NOT NULL,
    description_key VARCHAR(240) NOT NULL,
    definition_digest CHAR(64) NOT NULL CHECK (definition_digest ~ '^[0-9a-f]{64}$'),
    created_by UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activated_by UUID,
    activated_at TIMESTAMPTZ,
    retired_by UUID,
    retired_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT uq_sys_product_access_package_public UNIQUE (public_id),
    CONSTRAINT uq_sys_product_access_package_version UNIQUE (product_key, package_code, catalog_version),
    CONSTRAINT uq_sys_product_access_package_identity UNIQUE (package_id, public_id, catalog_version),
    CONSTRAINT ck_sys_product_access_package_four_eyes CHECK (
        activated_by IS NULL OR activated_by <> created_by
    ),
    CONSTRAINT ck_sys_product_access_package_lifecycle CHECK (
        (lifecycle_state = 'DRAFT'
            AND activated_by IS NULL AND activated_at IS NULL
            AND retired_by IS NULL AND retired_at IS NULL)
        OR (lifecycle_state = 'ACTIVE'
            AND activated_by IS NOT NULL AND activated_at IS NOT NULL
            AND retired_by IS NULL AND retired_at IS NULL)
        OR (lifecycle_state = 'RETIRED'
            AND activated_by IS NOT NULL AND activated_at IS NOT NULL
            AND retired_by IS NOT NULL AND retired_at IS NOT NULL)
    )
);


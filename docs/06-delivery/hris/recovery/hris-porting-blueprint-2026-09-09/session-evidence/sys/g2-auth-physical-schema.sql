CREATE OR REPLACE FUNCTION sys_guard_product_access_package_lifecycle() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.lifecycle_state <> 'DRAFT' THEN
            RAISE EXCEPTION 'PRODUCT_ACCESS_PACKAGE_MUST_START_DRAFT' USING ERRCODE = '55000';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        IF OLD.lifecycle_state <> 'DRAFT' THEN
            RAISE EXCEPTION 'PRODUCT_ACCESS_PACKAGE_HISTORY_CANNOT_BE_DELETED' USING ERRCODE = '55000';
        END IF;
        RETURN OLD;
    END IF;
    IF OLD.lifecycle_state = 'RETIRED' AND NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_PACKAGE_RETIREMENT_MONOTONIC' USING ERRCODE = '55000';
    END IF;
    IF OLD.lifecycle_state <> NEW.lifecycle_state AND NOT (
        (OLD.lifecycle_state = 'DRAFT' AND NEW.lifecycle_state = 'ACTIVE')
        OR (OLD.lifecycle_state = 'ACTIVE' AND NEW.lifecycle_state = 'RETIRED')
    ) THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_PACKAGE_INVALID_STATE_TRANSITION' USING ERRCODE = '55000';
    END IF;
    IF OLD.lifecycle_state = 'ACTIVE'
       AND (to_jsonb(NEW) - ARRAY['lifecycle_state','retired_by','retired_at','version'])
           IS DISTINCT FROM
           (to_jsonb(OLD) - ARRAY['lifecycle_state','retired_by','retired_at','version']) THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_PACKAGE_ACTIVE_DEFINITION_IMMUTABLE' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION sys_guard_product_access_package_role_mutation() RETURNS trigger AS $$
DECLARE old_package_state VARCHAR(24);
DECLARE new_package_state VARCHAR(24);
BEGIN
    IF TG_OP = 'INSERT' THEN
        SELECT lifecycle_state INTO new_package_state
          FROM sys_product_access_package_catalog
         WHERE package_id = NEW.package_id;
        IF new_package_state IS NOT NULL AND new_package_state <> 'DRAFT' THEN
            RAISE EXCEPTION 'PRODUCT_ACCESS_PACKAGE_ROLE_DRAFT_ONLY' USING ERRCODE = '55000';
        END IF;
        RETURN NEW;
    END IF;
    SELECT lifecycle_state INTO old_package_state
      FROM sys_product_access_package_catalog
     WHERE package_id = OLD.package_id;
    IF TG_OP = 'DELETE' THEN
        IF old_package_state IS DISTINCT FROM 'DRAFT' THEN
            RAISE EXCEPTION 'PRODUCT_ACCESS_PACKAGE_ROLE_DRAFT_ONLY' USING ERRCODE = '55000';
        END IF;
        RETURN OLD;
    END IF;
    SELECT lifecycle_state INTO new_package_state
      FROM sys_product_access_package_catalog
     WHERE package_id = NEW.package_id;
    IF old_package_state IS DISTINCT FROM 'DRAFT'
       OR new_package_state IS DISTINCT FROM 'DRAFT' THEN
        RAISE EXCEPTION 'PRODUCT_ACCESS_PACKAGE_ROLE_DRAFT_ONLY' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


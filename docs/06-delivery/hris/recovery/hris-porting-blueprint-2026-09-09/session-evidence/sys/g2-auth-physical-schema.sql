CREATE OR REPLACE FUNCTION com_product_access_guard_command_receipt_seal()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Auth HRIS command receipt cannot be deleted';
    END IF;
    IF ROW(NEW.tenant_id, NEW.command_type, NEW.originating_action,
           NEW.subject_principal_public_id, NEW.population_scope_digest,
           NEW.field_policy_revision, NEW.purpose_code,
           NEW.authorization_revision, NEW.idempotency_key,
           NEW.request_digest, NEW.correlation_id)
       IS DISTINCT FROM
       ROW(OLD.tenant_id, OLD.command_type, OLD.originating_action,
           OLD.subject_principal_public_id, OLD.population_scope_digest,
           OLD.field_policy_revision, OLD.purpose_code,
           OLD.authorization_revision, OLD.idempotency_key,
           OLD.request_digest, OLD.correlation_id) THEN
        RAISE EXCEPTION 'Auth HRIS command receipt authorization and idempotency seal is immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tr_com_product_access_command_receipt_seal
    BEFORE UPDATE OR DELETE ON com_product_access_command_receipts
    FOR EACH ROW EXECUTE FUNCTION com_product_access_guard_command_receipt_seal();

-- Service-local outbox, inbox and audit tables reuse the dwp-core Auth migration
-- baseline. The HRIS command receipt is owner-local because its originating
-- authorization and caller-bound idempotency context must be immutable.
-- Runtime roles are NOINHERIT, NOSUPERUSER and NOBYPASSRLS. The transaction
-- interceptor must SET LOCAL dwp.tenant_id after verified tenant resolution.
DO $$
DECLARE target_table TEXT;
BEGIN
  FOREACH target_table IN ARRAY ARRAY[
    'com_product_access_package_assignments',
    'com_product_access_package_policy_refs',
    'com_product_access_package_projection_status',
    'com_product_access_command_receipts'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', target_table);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', target_table);
    EXECUTE format(
      'CREATE POLICY %I ON %I USING (tenant_id = NULLIF(current_setting(''dwp.tenant_id'', true), '''')::BIGINT) WITH CHECK (tenant_id = NULLIF(current_setting(''dwp.tenant_id'', true), '''')::BIGINT)',
      target_table || '_tenant_policy', target_table
    );
  END LOOP;
END $$;

COMMIT;

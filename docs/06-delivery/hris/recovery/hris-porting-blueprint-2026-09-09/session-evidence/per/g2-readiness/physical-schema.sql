-- Row-level security is defense in depth. The application PEP remains authoritative.
-- API/worker roles are NOINHERIT, NOSUPERUSER and NOBYPASSRLS. The audited migration/
-- maintenance role owns tables. DWP transaction scope sets dwp.tenant_id after SET LOCAL
-- ROLE and the pool must reset both before reuse.
DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'prf_cycles','prf_cycle_versions','prf_cycle_stages','prf_templates','prf_template_versions',
        'prf_template_items','prf_rubric_levels','prf_population_rules','prf_population_freezes',
        'prf_participants','prf_reviewer_assignments','prf_goals','prf_goal_revisions',
        'prf_goal_alignments','prf_reviews','prf_review_submissions','prf_review_answers',
        'prf_feedback_requests','prf_feedback_assignments','prf_feedback_responses','prf_checkins',
        'prf_calibration_sessions','prf_calibration_adjustments','prf_result_sets','prf_results',
        'prf_result_publications','prf_appeals','prf_appeal_events','prf_evidence_refs',
        'prf_command_receipts','prf_inbox_receipts','prf_outbox_events','prf_import_runs','prf_import_row_issues'
    ] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', table_name);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', table_name);
        EXECUTE format(
            'CREATE POLICY %I ON %I USING (tenant_id = NULLIF(current_setting(''dwp.tenant_id'', true), '''')::BIGINT) WITH CHECK (tenant_id = NULLIF(current_setting(''dwp.tenant_id'', true), '''')::BIGINT)',
            table_name || '_tenant_policy', table_name
        );
    END LOOP;
END $$;


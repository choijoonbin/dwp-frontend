CREATE OR REPLACE FUNCTION prf_guard_population_rule_publication_lineage() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.published_at IS NOT NULL THEN
        IF NEW.published_at IS DISTINCT FROM OLD.published_at
           OR NEW.scope_type IS DISTINCT FROM OLD.scope_type
           OR NEW.scope_public_id IS DISTINCT FROM OLD.scope_public_id
           OR NEW.rule_key IS DISTINCT FROM OLD.rule_key
           OR NEW.version_no IS DISTINCT FROM OLD.version_no
           OR NEW.rule_schema_version IS DISTINCT FROM OLD.rule_schema_version
           OR NEW.rule_definition IS DISTINCT FROM OLD.rule_definition
           OR NEW.content_hash IS DISTINCT FROM OLD.content_hash
           OR NEW.effective_from IS DISTINCT FROM OLD.effective_from THEN
            RAISE EXCEPTION 'PER_POPULATION_RULE_PUBLISHED_LINEAGE_IMMUTABLE' USING ERRCODE = '55000';
        END IF;
        IF NEW.effective_to IS DISTINCT FROM OLD.effective_to
           AND NOT (
               OLD.effective_to IS NULL
               AND NEW.effective_to IS NOT NULL
               AND NEW.effective_to > OLD.effective_from
           ) THEN
            RAISE EXCEPTION 'PER_POPULATION_RULE_PERIOD_REWRITE_FORBIDDEN' USING ERRCODE = '55000';
        END IF;
    ELSIF NEW.rule_state IN ('PUBLISHED','SUPERSEDED') THEN
        NEW.published_at := COALESCE(NEW.published_at, CURRENT_TIMESTAMP);
    ELSIF NEW.published_at IS NOT NULL THEN
        RAISE EXCEPTION 'PER_POPULATION_RULE_MARKER_WITHOUT_PUBLISHED_STATE' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_prf_population_rule_publication_lineage
    BEFORE INSERT OR UPDATE ON prf_population_rules
    FOR EACH ROW EXECUTE FUNCTION prf_guard_population_rule_publication_lineage();


CREATE OR REPLACE FUNCTION prf_guard_command_receipt_originating_auth()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'PER command receipt cannot be deleted';
    END IF;
    IF ROW(NEW.tenant_id, NEW.command_type, NEW.idempotency_key,
           NEW.request_hash, NEW.actor_user_id,
           NEW.originating_action, NEW.subject_principal_public_id,
           NEW.population_scope_digest, NEW.field_policy_revision,
           NEW.purpose_code, NEW.authorization_revision,
           NEW.originating_context_sealed_at, NEW.originating_context_digest)
       IS DISTINCT FROM
       ROW(OLD.tenant_id, OLD.command_type, OLD.idempotency_key,
           OLD.request_hash, OLD.actor_user_id,
           OLD.originating_action, OLD.subject_principal_public_id,
           OLD.population_scope_digest, OLD.field_policy_revision,
           OLD.purpose_code, OLD.authorization_revision,
           OLD.originating_context_sealed_at, OLD.originating_context_digest) THEN
        RAISE EXCEPTION 'PER command receipt originating authorization and caller-bound idempotency context is immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_prf_command_receipt_originating_auth
    BEFORE UPDATE OR DELETE ON prf_command_receipts
    FOR EACH ROW EXECUTE FUNCTION prf_guard_command_receipt_originating_auth();

